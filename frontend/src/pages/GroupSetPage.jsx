import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { getGroupSet } from '../services/groupSetsApi.js'

const format = (value) => value.toFixed(2)
const percent = (value) => `${Math.round(value * 100)}%`

function GroupCard({ group }) {
  return (
    <section>
      <div className="group-card-header">
        <h2>Group {group.number}</h2>
        <span className="score-value" title="Group score: importance-weighted strength in the project's competencies">
          {format(group.score)}
        </span>
      </div>

      <ul className="member-list">
        {group.members.map((member) => (
          <li key={member.studentId}>
            <Link to={`/students/${member.studentId}`}>{member.name}</Link>
            <span className="muted small">{member.studentNumber}</span>
            {member.strongestCompetency && <span className="badge">{member.strongestCompetency}</span>}
            {member.lowEvidence && (
              <span className="badge badge-warn" title="No grades yet: placed using the teacher's estimate or the class average">
                no grades yet
              </span>
            )}
          </li>
        ))}
      </ul>

      <h3>Strength per competency</h3>
      {group.competencies.map((c) => (
        <div key={c.code} className="strength-row" title={`Carried by ${c.carriedBy}`}>
          <span>{c.name}</span>
          <div className="score-track">
            <div className="score-fill" style={{ width: percent(c.strength) }} />
          </div>
          <span className="score-value">{format(c.strength)}</span>
        </div>
      ))}

      <p className="small">
        <strong>Why together: </strong>
        {group.strengths.length > 0 ? `strong in ${group.strengths.join(' and ')}` : 'no clear strength'}
        {group.competencies[0] && `, led in ${group.competencies[0].name} by ${group.competencies[0].carriedBy}`}.
      </p>
      {group.gaps.length > 0 && (
        <div className="chips">
          <span className="small muted">Gaps:</span>
          {group.gaps.map((gap) => (
            <span key={gap} className="badge badge-warn">
              {gap}
            </span>
          ))}
        </div>
      )}
    </section>
  )
}

// One saved generation of groups, with the explanation of why students were grouped together.
export default function GroupSetPage() {
  const { id } = useParams()
  const [set, setSet] = useState(null)
  const [error, setError] = useState(null)

  useEffect(() => {
    getGroupSet(id)
      .then(setSet)
      .catch((err) => setError(err.message))
  }, [id])

  if (error) {
    return <p className="alert alert-error">{error}</p>
  }
  if (!set) {
    return <p className="muted">Loading…</p>
  }

  const balanced = set.strategy === 'BALANCED'
  const sizes = set.groups.map((g) => g.members.length).join(' + ')

  return (
    <>
      <p>
        <Link to={`/projects/${set.projectId}`}>← {set.projectName}</Link>
      </p>
      <div className="page-header">
        <h1>Groups of {new Date(set.generatedAt).toLocaleString('en-GB')}</h1>
      </div>
      <p className="muted">
        {balanced ? 'Balanced and complementary' : 'Random'} strategy · generated by {set.generatedBy} · group size{' '}
        {set.groupSize} · seed {set.seed}
      </p>

      <section>
        <div className="stat-grid">
          <div className="stat">
            <span className="stat-value">{set.groups.length}</span>
            <span className="stat-label">groups: {sizes}</span>
          </div>
          <div className="stat">
            <span className="stat-value">{format(set.weakestScore)}</span>
            <span className="stat-label">weakest group (random groups: {format(set.randomWeakestScore)})</span>
          </div>
          <div className="stat">
            <span className="stat-value">{format(set.averageScore)}</span>
            <span className="stat-label">average group</span>
          </div>
          <div className="stat">
            <span className="stat-value">{format(set.spread)}</span>
            <span className="stat-label">difference between strongest and weakest group</span>
          </div>
        </div>
        {set.warnings.map((warning) => (
          <p key={warning} className="alert alert-warn">
            {warning}
          </p>
        ))}
        <p className="small muted">
          A group&apos;s strength in a competency counts its best member and half of its second best, so groups need
          complementary students rather than several with the same strength. The balanced strategy makes the weakest
          group as strong as possible. Students without grades count as the class average, adjusted by any teacher
          estimate.
        </p>
      </section>

      <div className="group-grid">
        {set.groups.map((group) => (
          <GroupCard key={group.number} group={group} />
        ))}
      </div>
    </>
  )
}
